package com.eespindola.section.cadenas;

public class C11CaracteresEspeciales {
  public static void main(String[] args) {
    String cadena1 = "Hola\nMundo";
    System.out.println("cadena1 = " + cadena1);

    String cadena3 = "\tHola\tMundo";
    System.out.println("cadena3 = " + cadena3);

    String cadena4 = "Hola \' Mundo";
    System.out.println("cadena4 = " + cadena4);

    String cadena5 = "Hola \" Mundo";
    System.out.println("cadena5 = " + cadena5);

    String cadena6 = "Hola \\ Mundo";
    System.out.println("cadena6 = " + cadena6);

  }
}
